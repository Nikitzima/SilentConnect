    def _run_mihomo_validate(self, yaml_content: str) -> subprocess.CompletedProcess:
        """Runs mihomo.exe -t -f <temp_yaml> and returns completed process."""
        temp_yaml = os.path.join(self.temp_dir, f"test_clash_{time.time_ns()}.yaml")
        with open(temp_yaml, "w", encoding="utf-8") as f:
            f.write(yaml_content)

        res = subprocess.run(
            [MIHOMO_PATH, "-t", "-f", temp_yaml],
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=10,
        )
        return res

