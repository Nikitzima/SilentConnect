        yaml_out = subjson_app.build_clash_meta_config("MainDefConf", "sub.example.com", "global")
        doc = yaml.safe_load(yaml_out)

        # Monkeypatch yaml module import failure inside dump_clash_yaml
        orig_yaml = sys.modules.get("yaml")
        try:
            sys.modules["yaml"] = None
            fallback_yaml = subjson_app.dump_clash_yaml(doc)
        finally:
            if orig_yaml is not None:
                sys.modules["yaml"] = orig_yaml

        res = self._run_mihomo_validate(fallback_yaml)
        self.assertEqual(res.returncode, 0, f"Mihomo validation failed on fallback YAML generator:\nSTDOUT: {res.stdout}\nSTDERR: {res.stderr}")

